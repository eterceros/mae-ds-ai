// Esquema y datos de la demo. Los datos se generan dentro de Postgres con una semilla fija
// (setseed), así que dos ejecuciones con el mismo FILAS producen la misma tabla.
export function sqlEsquema() {
  return `
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_prewarm;
DROP TABLE IF EXISTS pedidos;
DROP TABLE IF EXISTS clientes;

CREATE TABLE clientes (
  id     integer PRIMARY KEY,
  nombre text NOT NULL,
  ciudad text NOT NULL
);

-- id es integer a propósito (el caso clásico de "se nos acaban los int").
CREATE TABLE pedidos (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id  integer NOT NULL,          -- sin FK al inicio: M6 la agrega
  producto_id integer NOT NULL,
  estado      text    NOT NULL,
  total       numeric(10,2) NOT NULL,
  region      text,                      -- anulable pero sin nulos: M5 la vuelve NOT NULL
  creado_en   timestamptz NOT NULL
);
`;
}

export function sqlDatos(filas, clientes, semilla) {
  // setseed recibe un valor entre -1 y 1.
  const s = ((semilla % 1000) / 1000).toFixed(3);
  return `
SELECT setseed(${s});
INSERT INTO clientes (id, nombre, ciudad)
SELECT g, 'cliente ' || g,
       (ARRAY['Cochabamba','La Paz','Santa Cruz','Sucre','Oruro','Tarija','Potosí','Trinidad','Cobija'])[1 + (g % 9)]
FROM generate_series(1, ${clientes}) g;

INSERT INTO pedidos (id, cliente_id, producto_id, estado, total, region, creado_en)
SELECT g,
       1 + floor(random() * ${clientes})::int,
       1 + floor(random() * 5000)::int,
       (ARRAY['nuevo','pagado','enviado','entregado','cancelado'])[1 + floor(random() * 5)::int],
       round((random() * 1000)::numeric, 2),
       (ARRAY['andina','valles','llanos'])[1 + floor(random() * 3)::int],
       timestamptz '2024-01-01' + (g::double precision / ${filas}) * interval '700 days'
FROM generate_series(1, ${filas}) g;

SELECT setval(pg_get_serial_sequence('pedidos', 'id'), ${filas});
CREATE INDEX pedidos_cliente_idx ON pedidos (cliente_id);
CREATE INDEX pedidos_creado_idx ON pedidos (creado_en);
VACUUM (ANALYZE) clientes;
VACUUM (ANALYZE) pedidos;
CHECKPOINT;
`;
}
